const { withAppBuildGradle } = require("expo/config-plugins");

const MARKER = "// @generated by with-android-release-signing";

const RELEASE_SIGNING_CONFIGURATION = `

${MARKER}
def yousufRiceReleaseSigning = [
    storeFile: System.getenv("YOUSUF_RICE_UPLOAD_STORE_FILE"),
    storePassword: System.getenv("YOUSUF_RICE_UPLOAD_STORE_PASSWORD"),
    keyAlias: System.getenv("YOUSUF_RICE_UPLOAD_KEY_ALIAS"),
    keyPassword: System.getenv("YOUSUF_RICE_UPLOAD_KEY_PASSWORD"),
]
def yousufRiceReleaseTaskRequested = gradle.startParameter.taskNames.any {
    it.toLowerCase().contains("release")
}
def yousufRiceMissingSigningValues = yousufRiceReleaseSigning.findAll {
    !it.value
}.keySet()

if (yousufRiceReleaseTaskRequested && !yousufRiceMissingSigningValues.isEmpty()) {
    throw new GradleException(
        "Missing Yousuf Rice Play upload signing values: " +
        yousufRiceMissingSigningValues.join(", ") +
        ". Use scripts/android-google-play.sh and .env.googleplay.local."
    )
}

android {
    signingConfigs {
        yousufRiceRelease {
            if (yousufRiceMissingSigningValues.isEmpty()) {
                storeFile file(yousufRiceReleaseSigning.storeFile)
                storePassword yousufRiceReleaseSigning.storePassword
                keyAlias yousufRiceReleaseSigning.keyAlias
                keyPassword yousufRiceReleaseSigning.keyPassword
            }
        }
    }
    buildTypes {
        release {
            signingConfig signingConfigs.yousufRiceRelease
        }
    }
}
`;

module.exports = function withAndroidReleaseSigning(config) {
  return withAppBuildGradle(config, (gradleConfig) => {
    if (gradleConfig.modResults.language !== "groovy") {
      throw new Error("Yousuf Rice Android signing requires Groovy Gradle.");
    }

    const contents = gradleConfig.modResults.contents;
    gradleConfig.modResults.contents = contents.includes(MARKER)
      ? contents
      : `${contents.trimEnd()}${RELEASE_SIGNING_CONFIGURATION}`;
    return gradleConfig;
  });
};
